export type WvStringKey = keyof typeof strings['zh-CN'];
export type Translate = (key: WvStringKey, vars?: Record<string, string>) => string;

export function makeT(locale: Locale): Translate {
  const table = strings[locale];
  return (key, vars) => {
    let s: string = table[key] ?? strings['en-US'][key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    }
    return s;
  };
}
